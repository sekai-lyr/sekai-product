"""Normalize completed generated sheets and register only assets present on disk."""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
STATIC = ROOT / 'src/main/resources/static'
TASKS = json.loads((ROOT / 'tools/independent-atlas-tasks.json').read_text('utf-8'))
registered = {}
for task in TASKS:
    source = ROOT / 'tools/independent-atlas-raw' / task['sheet']
    if not source.exists():
        continue
    target = STATIC / 'images/vfx' / task['sheet']
    if not target.exists() or source.stat().st_mtime > target.stat().st_mtime:
        raw = Image.open(source).convert('RGBA')
        if raw.getextrema()[3][0] != 0:
            print('REJECT opaque background:', task['id'])
            continue
        width, height = raw.size
        sheet = Image.new('RGBA', (1536, 1536))
        for index in range(16):
            x, y = index % 4, index // 4
            frame = raw.crop((round(x*width/4), round(y*height/4), round((x+1)*width/4), round((y+1)*height/4)))
            frame.thumbnail((384, 384), Image.Resampling.LANCZOS)
            sheet.alpha_composite(frame, (x*384+(384-frame.width)//2, y*384+(384-frame.height)//2))
        sheet.save(target, optimize=True)
    mobile = STATIC / 'images/vfx-mobile' / task['sheet'].replace('.png', '.webp')
    if not mobile.exists() or target.stat().st_mtime > mobile.stat().st_mtime:
        mobile.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(target) as atlas:
            atlas.resize((768, 768), Image.Resampling.LANCZOS).save(mobile, 'WEBP', quality=84, method=4)
    registered[task['id']] = task['sheet']

manifest = STATIC / 'js/independent-card-atlases.js'
pending_manifest = manifest.with_suffix('.js.tmp')
pending_manifest.write_text('// Completed independent 4×4 sprite sheets. Generated by tools/install-independent-atlases.py.\nexport const INDEPENDENT_CARD_ATLASES = '+json.dumps(registered, ensure_ascii=False, indent=4)+';\n', 'utf-8')
pending_manifest.replace(manifest)
status = {'required':len(TASKS), 'installed':len(registered), 'remaining':[t for t in TASKS if t['id'] not in registered]}
(ROOT / 'tools/independent-atlas-progress.json').write_text(json.dumps(status,ensure_ascii=False,indent=2),'utf-8')
print(json.dumps({'required':len(TASKS),'installed':len(registered),'remaining':len(status['remaining'])}))
