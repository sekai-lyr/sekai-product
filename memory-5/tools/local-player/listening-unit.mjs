import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
let time=0,tick;const calls=[];
const window={addEventListener(){}};
const context={window,performance:{now:()=>time},AbortController,setInterval(fn,ms){if(ms===1000)tick=fn;},fetch:async(url,options)=>{calls.push({url,options});return {ok:true,json:async()=>url.endsWith('/token')?{csrf:'test'}:{id:'test-session'}};}};
vm.runInNewContext(readFileSync('src/main/resources/static/js/listening-stats.js','utf8'),context);
class Audio extends EventTarget{paused=true;ended=false;seeking=false;readyState=4;currentTime=0;}
const drain=async()=>{for(let i=0;i<80;i++)await Promise.resolve();};
const audio=new Audio();window.__sekaiListening.attach(audio,{id:123,key:'account:31:123'},'disc');
time=1000;tick();assert.equal(calls.length,0,'Loading a song is not a play');
audio.paused=false;audio.dispatchEvent(new Event('playing'));await drain();
time+=1000;tick();audio.currentTime=180;audio.seeking=true;audio.dispatchEvent(new Event('seeking'));
time+=1000;tick();audio.seeking=false;audio.dispatchEvent(new Event('seeked'));time+=1000;tick();audio.paused=true;audio.dispatchEvent(new Event('pause'));await drain();
const reports=calls.filter(call=>call.options?.body && !call.url.endsWith('/start')).map(call=>JSON.parse(call.options.body));
assert.equal(reports.at(-1).cumulativeMs,2000,'Seek and paused intervals must not count');
const second=new Audio();window.__sekaiListening.attach(second,{id:123,key:'account:31:123'},'folia');second.paused=false;second.dispatchEvent(new Event('playing'));await drain();
assert.equal(calls.filter(call=>call.url.endsWith('/start')).length,1,'Changing stage must retain the play session');
time+=1000;tick();second.paused=true;second.dispatchEvent(new Event('pause'));await drain();
assert.equal(JSON.parse(calls.filter(call=>call.options?.body && !call.url.endsWith('/start')).at(-1).options.body).cumulativeMs,3000);
console.log('Listening: paused/seek excluded, stage switch retains session, no audio payload — PASS');
